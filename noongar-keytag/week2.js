  const pencil = '#7d8a80';
  const frame = `<circle cx="320" cy="215" r="170" fill="#fff" stroke="${pencil}" stroke-width="3" stroke-dasharray="2 0"/><circle cx="320" cy="68" r="13" fill="none" stroke="${pencil}" stroke-width="3"/>`;
  const a = svg(frame + glyph('swan', 315, 225, 230, pencil) + glyph('rain-drops', 215, 150, 70, pencil) + glyph('rain-drops', 420, 140, 60, pencil), 'Sketch A: one big swan with rain drops');
  const b = svg(frame + glyph('fish', 305, 180, 200, pencil) + glyph('waves', 320, 290, 200, pencil) + glyph('sun', 230, 110, 55, pencil) + glyph('sun', 410, 110, 55, pencil), 'Sketch B: fish over a band of waves');
