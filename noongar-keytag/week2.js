/* Week 2 visuals: idea bank, symbol story, shape breakdowns, templates.
   Motif drawings come from motifs.js (generated by tools/build_week2.py). */
const MOTIF = Object.fromEntries(MOTIF_LIBRARY.map(m => [m.id, m]));
const glyph = (id, x, y, size, color = '#203c41', rot = 0) =>
  `<g color="${color}" transform="${rot ? `rotate(${rot} ${x} ${y}) ` : ''}translate(${x - size / 2} ${y - size / 2}) scale(${size / 100})">${MOTIF[id].svg}</g>`;
const icon = (inner, label = '') => `<svg viewBox="0 0 100 100" role="img" aria-label="${label}">${inner}</svg>`;
const stars = n => '★'.repeat(n) + '<span class="dim">' + '★'.repeat(3 - n) + '</span>';
const fileUrl = f => encodeURI(f);

function motifWall() {
  const ids = ['sun', 'fish', 'swan', 'wattle', 'crab', 'blossom', 'lizard', 'rain-cloud', 'emu-tracks', 'wildflower', 'waves', 'nest'];
  return `<div class="motif-wall">${ids.map(id => `<div>${icon(MOTIF[id].svg, MOTIF[id].name)}</div>`).join('')}</div>`;
}

function ideaBank(s) {
  return `<div class="idea-bank">${s.ids.map(i => SEASON_IDEAS[i]).map(x => `<article class="idea-season ${x.id}">
    <header><h2>${x.name}</h2><span>${x.months} · ${x.title}</span></header>
    <p>${x.text}</p>
    <div class="idea-icons">${x.ideas.slice(0, 5).map(id => `<figure>${icon(MOTIF[id].svg, MOTIF[id].name)}<figcaption>${MOTIF[id].name.replace(/ \(.*\)/, '')}${MOTIF[id].word ? `<i>${MOTIF[id].word.replace(/ \(.*\)/, '')}</i>` : ''}</figcaption></figure>`).join('')}</div>
  </article>`).join('')}</div>`;
}

function symbolStory() {
  const art = svg(`<rect x="0" y="0" width="640" height="420" rx="26" fill="#f3efe4"/>
    ${glyph('campfire', 150, 215, 190)}
    ${glyph('emu-tracks', 330, 250, 150, '#203c41', 70)}
    ${glyph('waterhole', 500, 190, 170)}
    ${[150, 330, 500].map((x, i) => `<circle cx="${x}" cy="${i === 1 ? 360 : 360}" r="17" fill="#ae7633"/><text x="${x}" y="${367}" font-size="19" fill="#fff" text-anchor="middle" font-weight="700">${i + 1}</text>`).join('')}`,
    'A symbol story: people around a campfire, emu tracks, a waterhole');
  const read = [['campfire', 'People sitting around the campfire', 'karla'], ['emu-tracks', 'Emu tracks', 'waitj'], ['waterhole', 'A waterhole', 'ngaamar']];
  return `<div class="symbol-story"><div class="story-art">${art}</div><div class="story-read">
    ${read.map((r, i) => `<div class="read-row"><span class="read-no">${i + 1}</span>${icon(MOTIF[r[0]].svg, r[1])}<div><b>${r[1]}</b><i>${r[2]}</i></div></div>`).join('')}
    <p class="story-line">“People sat around the fire. An emu walked past to the waterhole.”</p></div></div>`;
}

function decompose() {
  return `<div class="decompose">${DECOMPOSE.map(d => `<div class="dec-row">
    ${d.parts.map((p, i) => `${i ? '<span class="op">+</span>' : ''}<div class="dec-part">${icon(p)}</div>`).join('')}
    <span class="op">=</span><div class="dec-final">${icon(d.final, d.name)}<b>${d.name}</b></div></div>`).join('')}</div>`;
}

function breakdown(s) {
  const b = BREAKDOWNS.find(x => x.id === s.motif);
  return `<div class="breakdown">
    <div class="bd-meta"><span class="bd-level">${stars(b.level)}</span><span>${b.seasons}</span><i>${b.word}</i></div>
    <div class="bd-steps">${b.steps.map((st, i) => `<div class="bd-step">
      <div class="bd-art"><span class="bd-no">${i + 1}</span>${icon(st.svg, `Step ${i + 1}`)}</div>
      <p>${st.cap}</p><kbd>${st.key}</kbd></div>`).join('<span class="bd-arrow">›</span>')}</div>
    <p class="bd-hint">Orange shows the new part in each step.</p></div>`;
}

function toolCard(s) {
  return `<div class="tool-card">${s.items.map(([k, what, how]) => `<div><kbd>${k}</kbd><b>${what}</b><small>${how}</small></div>`).join('')}</div>`;
}

